// ── Time budgeting ──────────────────────────────────────────────────

const WARMUP_COOLDOWN_MIN = 10;
const SECONDS_PER_SET = 45;

export function estimateExerciseMinutes(p: PlannedExercise): number {
  return (p.sets * (SECONDS_PER_SET + p.restSec)) / 60 + 1;
}

export function estimateSessionMinutes(session: Session): number {
  return Math.round(WARMUP_COOLDOWN_MIN + session.exercises.reduce((t, p) => t + estimateExerciseMinutes(p), 0));
}

// ── Plan generation ─────────────────────────────────────────────────

export const MAX_TRAINING_DAYS = 6;

function pickExercise(
  slot: Slot,
  ctx: EligibilityContext,
  inSession: Set<string>,
  usedThisWeek: Map<string, number>,
): Exercise | undefined {
  const cap = DIFFICULTY_CAP[ctx.experience];
  for (const pattern of slot.patterns) {
    const candidates = EXERCISES.filter((e) => e.pattern === pattern && !inSession.has(e.id) && isEligible(e, ctx));
    if (candidates.length === 0) continue;
    // Deterministic ranking: prefer compound movements (more muscles per
    // minute), then exercises used less this week (variety), then difficulty
    // closest to the user's level. Ties keep library order.
    return [...candidates].sort((a, b) => {
      if (a.compound !== b.compound) return a.compound ? -1 : 1;
      const used = (usedThisWeek.get(a.id) ?? 0) - (usedThisWeek.get(b.id) ?? 0);
      if (used !== 0) return used;
      return Math.abs(cap - a.difficulty) - Math.abs(cap - b.difficulty);
    })[0];
  }
  return undefined;
}

function warmupFor(title: string): string[] {
  const lower = /lower|legs/i.test(title);
  const upper = /upper|push|pull/i.test(title);
  return [
    '3–5 minutes of easy movement: brisk walk, cycling or marching on the spot.',
    lower && !upper
      ? '10 leg swings each side and 10 bodyweight squats.'
      : upper && !lower
        ? '10 arm circles each way and 10 band pull-aparts or wall push-ups.'
        : '10 arm circles, 10 bodyweight squats and 10 hip hinges.',
    'Do 1–2 lighter practice sets of your first exercise.',
  ];
}

const COOLDOWN = [
  '3–5 minutes of easy walking.',
  'Gentle stretches for the muscles you trained, 20–30 seconds each. No bouncing.',
];

export interface GenerateOptions {
  /** Monday of the week as YYYY-MM-DD. */
  weekStart: string;
}

export function buildSession(
  template: Template,
  day: Weekday,
  weekStart: string,
  profile: Profile,
  usedThisWeek: Map<string, number>,
): Session {
  const ctx = eligibilityFromProfile(profile);
  const inSession = new Set<string>();
  const exercises: PlannedExercise[] = [];
  let minutes = WARMUP_COOLDOWN_MIN;
  for (const slot of template.slots) {
    const ex = pickExercise(slot, ctx, inSession, usedThisWeek);
    if (!ex) continue;
    const rx = prescribe(ex, profile.goal, profile.experience);
    const planned: PlannedExercise = { exerciseId: ex.id, ...rx };
    const cost = estimateExerciseMinutes(planned);
    // Always keep at least two exercises so a short session is still useful.
    // If this one does not fit, a shorter exercise in a later slot still might.
    if (exercises.length >= 2 && minutes + cost > profile.sessionMinutes) continue;
    exercises.push(planned);
    inSession.add(ex.id);
    usedThisWeek.set(ex.id, (usedThisWeek.get(ex.id) ?? 0) + 1);
    minutes += cost;
  }
  return {
    id: `${weekStart}-d${day}`,
    day,
    title: template.title,
    exercises,
    status: 'planned',
    warmup: warmupFor(template.title),
    cooldown: COOLDOWN,
  };
}

/**
 * Generates a weekly plan using a fixed split chosen by the number of
 * training days, the user's equipment, experience and limitations.
 * Fully deterministic: the same profile and week always give the same plan.
 */
export function generateWeeklyPlan(profile: Profile, opts: GenerateOptions): WeeklyPlan {
  const changeLog: WeeklyPlan['changeLog'] = [];
  let days = [...new Set(profile.trainingDays)].sort((a, b) => a - b) as Weekday[];
  if (days.length === 0) days = [0, 2, 4];
  if (days.length > MAX_TRAINING_DAYS) {
    days = days.slice(0, MAX_TRAINING_DAYS);
    changeLog.push({
      at: opts.weekStart,
      description: 'We kept one full rest day each week. Rest helps your muscles recover and grow.',
    });
  }
  const templates = templatesFor(days.length);
  const used = new Map<string, number>();
  const sessions = days.map((day, i) => buildSession(templates[i]!, day, opts.weekStart, profile, used));
  changeLog.unshift({ at: opts.weekStart, description: `Plan created with ${sessions.length} training days.` });
  const plan: WeeklyPlan = { weekStart: opts.weekStart, sessions, changeLog };
  const gaps = neglectedMuscles(coverageReport(planVolume(plan), profile.experience));
  if (gaps.length > 0) {
    changeLog.push({
      at: opts.weekStart,
      description: `With your current equipment and time, ${listMuscles(gaps)} get little work this week. Adding training time or simple equipment like a resistance band would help.`,
    });
  }
  return plan;
}

export function swapExerciseInPlan(
  plan: WeeklyPlan,
  sessionId: string,
  fromId: string,
  toId: string,
  at: string,
  profile: Pick<Profile, 'goal' | 'experience'>,
): WeeklyPlan {
  const from = requireExercise(fromId);
  const to = requireExercise(toId);
  const rx = prescribe(to, profile.goal, profile.experience);
  return {
    ...plan,
    sessions: plan.sessions.map((s) =>
      s.id !== sessionId
        ? s
        : {
            ...s,
            exercises: s.exercises.map((p) =>
              p.exerciseId === fromId ? { exerciseId: toId, ...rx, note: `Swapped in for ${from.name}.` } : p,
            ),
          },
    ),
    changeLog: [...plan.changeLog, { at, description: `Swapped ${from.name} for ${to.name}.` }],
  };
}
