const DIFFICULTY_CAP: Record<Experience, 1 | 2 | 3> = { beginner: 1, intermediate: 2, advanced: 3 };

export interface EligibilityContext {
  equipment: Equipment[];
  limitations: Limitation[];
  experience: Experience;
  disliked?: string[];
}

export function hasEquipment(ex: Exercise, available: Equipment[]): boolean {
  return ex.equipment.every((e) => e === 'bodyweight' || available.includes(e));
}

/** Why an exercise is not suggested for this user, or null if it is fine. */
export function ineligibilityReason(ex: Exercise, ctx: EligibilityContext): string | null {
  if (!hasEquipment(ex, ctx.equipment)) return 'needs equipment you do not have';
  if (ex.difficulty > DIFFICULTY_CAP[ctx.experience]) return 'more advanced than your current level';
  const clash = ex.avoidWith.find((l) => ctx.limitations.includes(l));
  if (clash) return `not suggested with ${clash.replace('_', ' ')} discomfort`;
  if (ctx.disliked?.includes(ex.id)) return 'you marked it as disliked';
  return null;
}

export function isEligible(ex: Exercise, ctx: EligibilityContext): boolean {
  return ineligibilityReason(ex, ctx) === null;
}

export function eligibilityFromProfile(p: Profile): EligibilityContext {
  return {
    equipment: p.equipment,
    limitations: p.limitations,
    experience: p.experience,
    disliked: p.dislikedExercises,
  };
}

// ── Prescription rules ──────────────────────────────────────────────

export interface Prescription {
  sets: number;
  repsMin: number;
  repsMax: number;
  restSec: number;
  note?: string;
}

const LEVEL: Record<Experience, 0 | 1 | 2> = { beginner: 0, intermediate: 1, advanced: 2 };

/**
 * Explicit training rules. Values are conservative defaults intended for
 * review by a qualified trainer; they are not generated by a language model.
 */
export function prescribe(ex: Exercise, goal: Goal, experience: Experience): Prescription {
  const lvl = LEVEL[experience];
  if (ex.pattern === 'core_stability') {
    const holds: [number, number][] = [
      [20, 30],
      [30, 45],
      [45, 60],
    ];
    const [repsMin, repsMax] = holds[lvl]!;
    return { sets: lvl === 0 ? 2 : 3, repsMin, repsMax, restSec: 45, note: 'Numbers are seconds to hold.' };
  }

  const pick = <T>(arr: [T, T, T]): T => arr[lvl];

  if (ex.compound) {
    switch (goal) {
      case 'strength':
        return lvl === 0
          ? { sets: 3, repsMin: 6, repsMax: 10, restSec: 120 }
          : { sets: pick([3, 4, 5]), repsMin: 4, repsMax: 6, restSec: 180 };
      case 'muscle_growth':
        return { sets: pick([3, 3, 4]), repsMin: 8, repsMax: 12, restSec: 120 };
      case 'general_fitness':
        return { sets: pick([2, 3, 3]), repsMin: 10, repsMax: 15, restSec: 90 };
      case 'endurance':
        return { sets: pick([2, 3, 3]), repsMin: 15, repsMax: 20, restSec: 60 };
    }
  }
  switch (goal) {
    case 'strength':
      return { sets: pick([2, 3, 3]), repsMin: 8, repsMax: 12, restSec: 75 };
    case 'muscle_growth':
      return { sets: pick([2, 3, 3]), repsMin: 10, repsMax: 15, restSec: 75 };
    case 'general_fitness':
      return { sets: pick([2, 2, 3]), repsMin: 12, repsMax: 15, restSec: 60 };
    case 'endurance':
      return { sets: pick([2, 2, 3]), repsMin: 15, repsMax: 20, restSec: 45 };
  }
}

export function progressionTip(p: PlannedExercise): string {
  const ex = requireExercise(p.exerciseId);
  if (ex.pattern === 'core_stability') {
    return `When you can hold for ${p.repsMax} seconds on every set, add 5–10 seconds next time.`;
  }
  const load = ex.equipment.includes('bodyweight')
    ? 'try a harder version or add a few reps'
    : 'add the smallest weight step available';
  return `When you can do ${p.repsMax} good reps on every set, ${load} next time. Stop the set if your form breaks down.`;
}

